PLOT_LABEL_RULES = """
【plot_label 剧情标签】（4-10个汉字，本轮有重大事件时生成，否则空字符串）

必须生成标签的场景：
① 获得物品/能力："获得玄铁剑"、"领悟剑气"
② 场景切换："踏入皇城"、"进入秘境"
③ 关系变化："与女主结为道侣"、"师徒反目"
④ 重要事件："触发上古遗迹"、"Boss战爆发"
⑤ 重大抉择："选择加入魔教"、"接受传承"
⑥ 信息揭示："发现灭门真凶"、"得知身世秘密"
⑦ 危险/战斗："遭遇埋伏"、"陷入绝境"

不需要生成标签的场景：日常闲聊、纯氛围渲染、重复当前场景、纯心理活动

格式规范：优先"动词+名词"结构，如"获得XX"、"进入XX"
"""

